test('real capture-to-Focus journey updates the task, project, goal, Dashboard and worker notification', async ({ page, context, account }) => {
  const goal = await account.call('POST', 'goals', { title: 'Finish the personal journey', type: 'monthly', metadata: { progressMode: 'auto' } }, 201);
  const project = await account.call('POST', 'projects', { name: 'Personal journey project', goalId: goal.id }, 201);
  await account.signIn(page);
  await page.goto('/app/inbox');
  await page.getByRole('button', { name: 'Capture something', exact: true }).click();
  const capture = page.getByRole('dialog', { name: 'Quick capture' });
  await capture.getByLabel('Title', { exact: true }).fill('A real captured task');
  await capture.getByLabel('Details', { exact: true }).fill('Follow this task through the entire workspace.');
  await capture.getByRole('button', { name: 'Save to Inbox', exact: true }).click();
  await expect(capture).not.toBeVisible();
  await page.getByRole('button', { name: 'Schedule today: A real captured task', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Schedule today: A real captured task', exact: true })).toHaveCount(0);
  let task = (await account.call('GET', 'tasks')).find((item: any) => item.title === 'A real captured task');
  const day = (await account.call('GET', 'dashboard')).dateKey;
  expect(task.status).toBe('TODO'); expect(task.scheduledDate.slice(0, 10)).toBe(day); expect(task.metadata.inbox).toBe(false);
  await page.goto(`/app/board?task=${task.id}`);
  const details = page.getByRole('dialog');
  await details.getByLabel('Project Scope', { exact: true }).selectOption(project.id);
  await details.getByLabel('Estimate (Minutes)', { exact: true }).fill('1');
  await details.getByRole('button', { name: 'Save Changes', exact: true }).click();
  await expect(details).not.toBeVisible();
  expect((await account.call('GET', `planner/week?start=${day}&end=${day}`)).tasks.some((item: any) => item.id === task.id)).toBe(true);
  await page.goto('/app/planner?mode=day&date=' + day);
  await expect(page.getByText(task.title, { exact: true }).first()).toBeVisible();
  await page.getByRole('link', { name: /^Dashboard/ }).click();
  await page.getByLabel('0/3 priorities chosen', { exact: true }).selectOption(task.id);
  const start = page.getByRole('button', { name: 'Start Focus', exact: true });
  await expect(start).toBeEnabled();
  expect((await account.call('GET', 'focus-sessions/schedule')).plan.some((slot: any) => slot.taskId === task.id)).toBe(true);
  const opened = context.waitForEvent('page');
  await start.click();
  const focus = await opened;
  await expect(focus).toHaveURL(new RegExp(`/focus\\?task=${task.id}&date=${day}`));
  const setup = focus.getByRole('dialog', { name: 'Plan your focus time' });
  await expect(setup).toBeVisible();
  // Exercise an actual minute-long completion without waiting a real minute.
  // Both fake start/end instants remain in the past relative to the API clock.
  await focus.clock.install({ time: new Date(Date.now() - 120_000) });
  await setup.getByRole('button', { name: 'Use this plan' }).click();
  await focus.evaluate(() => (document.activeElement as HTMLElement)?.blur());
  await focus.keyboard.press('Space');
  await focus.clock.runFor(61_000);
  const decision = focus.getByRole('dialog', { name: 'Is this task done?' });
  await expect(decision).toBeVisible({ timeout: 15_000 });
  await decision.getByRole('button', { name: 'Mark task done', exact: true }).click();
  await expect.poll(async () => (await account.call('GET', `tasks/${task.id}`)).status).toBe('DONE');
  await expect.poll(async () => (await account.call('GET', `goals/${goal.id}`)).progress).toBe(100);
  await expect.poll(async () => (await account.call('GET', 'dashboard')).projects.find((item: any) => item.id === project.id)?.progress).toBe(100);
  await expect.poll(async () => (await account.call('GET', 'notifications')).filter((item: any) => item.metadata?.taskId === task.id).length, { timeout: 15_000 }).toBe(1);
  const dashboard = await account.call('GET', 'dashboard');
  expect(dashboard.today.focusSessions.filter((item: any) => item.taskId === task.id)).toHaveLength(1);
  expect(dashboard.today.focusMinutes).toBe(1);
  expect(dashboard.workspace.productivityScore).toBe(10);
  await page.bringToFront();
  await expect(page.getByRole('button', { name: `Reopen task ${task.title}`, exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button', { name: `Reopen task ${task.title}`, exact: true })).toBeVisible();
  await focus.close();
});

