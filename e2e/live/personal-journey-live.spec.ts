test('an active Focus session retains its task after Planner relinking and recovers a failed save after reload', async ({ page, account }) => {
  const day = (await account.call('GET', 'dashboard')).dateKey;
  const original = await account.call('POST', 'tasks', { title: 'Original focused task', status: 'TODO', estimateMinutes: 1 }, 201);
  const replacement = await account.call('POST', 'tasks', { title: 'Replacement reservation', status: 'TODO', estimateMinutes: 1 }, 201);
  const block = await account.call('POST', 'planner/time-blocks', { title: 'One minute reservation', type: 'WORK', date: day, startTime: '09:00', endTime: '09:01', taskId: original.id }, 201);
  await account.signIn(page);
  await page.goto(`/focus?task=${original.id}&block=${block.id}&date=${day}`);
  const setup = page.getByRole('dialog', { name: 'Plan your focus time' });
  await expect(setup).toBeVisible();
  let failSave = true;
  const attempts: any[] = [];
  await page.route('**/api/v1/focus-sessions', async route => {
    if (route.request().method() !== 'POST') return route.continue();
    attempts.push(route.request().postDataJSON());
    if (failSave) return route.fulfill({ status: 503, json: { message: 'Simulated save outage' } });
    return route.continue();
  });
  await page.clock.install({ time: new Date(Date.now() - 180_000) });
  await setup.getByRole('button', { name: 'Use this plan' }).click();
  await page.evaluate(() => (document.activeElement as HTMLElement)?.blur());
  await page.keyboard.press('Space');
  await page.clock.runFor(20_000);
  await account.call('PATCH', `planner/time-blocks/${block.id}`, { taskId: replacement.id });
  await page.clock.runFor(41_000);
  const retry = page.getByRole('button', { name: 'Retry saving session', exact: true });
  for (let index = 0; index < 8 && !await retry.isVisible(); index++) await page.clock.runFor(5_000);
  await expect(retry).toBeVisible();
  expect(attempts).toHaveLength(3);
  expect(attempts.every(attempt => attempt.taskId === original.id && attempt.completionId === attempts[0].completionId)).toBe(true);
  failSave = false;
  await page.reload();
  await expect(page.getByText('This scheduled task is unavailable. Return to Planner.', { exact: true })).toBeVisible();
  await expect(retry).toBeEnabled();
  const saved = page.waitForResponse(response => response.url().endsWith('/api/v1/focus-sessions') && response.request().method() === 'POST' && response.status() === 201);
  await retry.click();
  await saved;
  await expect(retry).not.toBeVisible();
  await expect.poll(async () => (await account.call('GET', 'dashboard')).today.focusSessions.filter((session: any) => session.id === attempts[0].completionId).length).toBe(1);
  const dashboard = await account.call('GET', 'dashboard');
  const sessions = dashboard.today.focusSessions.filter((session: any) => session.id === attempts[0].completionId);
  expect(sessions).toHaveLength(1); expect(sessions[0].taskId).toBe(original.id); expect(sessions[0].duration).toBe(60);
});

test('a real exported personal workspace restores with links and history into a separate workspace', async ({ page, account }) => {
  const goal = await account.call('POST', 'goals', { title: 'Restorable goal', type: 'yearly' }, 201);
  const project = await account.call('POST', 'projects', { name: 'Restorable project', goalId: goal.id }, 201);
  const task = await account.call('POST', 'tasks', { title: 'Restorable task', projectId: project.id }, 201);
  const backup = await account.call('GET', 'workspaces/export');
  await account.signIn(page);
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: /^Restore backup/ }).click();
  const dialog = page.getByRole('dialog', { name: 'Restore personal workspace', exact: true });
  await dialog.getByLabel('Backup file', { exact: true }).setInputFiles({ name: 'personal-backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup)) });
  await dialog.getByRole('button', { name: 'Restore as new workspace', exact: true }).click();
  await expect(dialog.getByRole('status')).toContainText('Your original workspace is unchanged.');
  const restored = (await account.call('GET', 'workspaces')).find((workspace: any) => workspace.id !== account.workspaceId && workspace.name.endsWith('(restored)'));
  expect(restored).toBeTruthy();
  const copied = (await account.call('GET', 'tasks', undefined, 200, restored.id)).find((entry: any) => entry.title === task.title);
  expect(copied.id).not.toBe(task.id); expect(copied.projectId).not.toBe(project.id);
  const copiedProject = await account.call('GET', `projects/${copied.projectId}`, undefined, 200, restored.id);
  expect(copiedProject.goalId).not.toBe(goal.id);
  const copiedGoal = await account.call('GET', `goals/${copiedProject.goalId}`, undefined, 200, restored.id);
  expect(copiedGoal.title).toBe(goal.title);
  expect(copiedGoal.snapshots.length).toBe((await account.call('GET', `goals/${goal.id}`)).snapshots.length);
  expect((await account.call('GET', `tasks/${task.id}`)).projectId).toBe(project.id);
  await dialog.getByRole('button', { name: 'Open restored workspace' }).click();
  await expect(page.getByRole('button', { name: 'Settings', exact: true })).toBeVisible();
});
